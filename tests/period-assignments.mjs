import assert from 'node:assert/strict';
import {defaultState,migrateState,validateState} from '../model.js';
import {calendarStats} from '../calendar.js';
import {actualDayRows,saveActualDay,subjectProgress} from '../actuals.js';
import {periodAssignmentIssues,periodAllocationSummary,resolvePeriodPlacement,resolveDatedPlacements,weeklyPeriodOverrides,estimatePeriodSchedule} from '../period-assignments.js';
import {mondayFor} from '../weekly.js';
const state=defaultState(),cl=state.resources.classes.find(c=>c.grade===3);
const lesson=state.lessons.find(l=>l.subject==='技術・家庭'&&l.classIds.length===1&&l.classIds[0]===cl.id);
assert(lesson,'year-3 technology/home course should exist');
const teachers=state.resources.teachers;
const room=state.resources.facilities.find(f=>f.id==='tech');
const fy=Number(state.school.fiscalYear);
const tech={id:'period_tech',classId:cl.id,baseSubject:'技術・家庭',label:'技術分野',startDate:fy+'-04-01',endDate:fy+'-09-30',targetHours:18,teacherId:teachers[0].id,facilityId:room?.id||''};
const home={id:'period_home',classId:cl.id,baseSubject:'技術・家庭',label:'家庭分野',startDate:fy+'-10-01',endDate:(fy+1)+'-03-31',targetHours:17,teacherId:teachers[1].id,facilityId:''};
assert.deepEqual(periodAssignmentIssues(state,tech),[]);
state.periodAssignments=[tech];
assert.deepEqual(periodAssignmentIssues(state,home),[]);
state.periodAssignments.push(home);
const summary=periodAllocationSummary(state,cl.id,'技術・家庭');
assert.equal(summary.target,35);assert.equal(summary.allocated,35);assert.equal(summary.remaining,0);
const overlapping={...home,id:'extra',startDate:fy+'-09-29'};
assert(periodAssignmentIssues(state,overlapping).some(x=>x.includes('重複')));
assert(periodAssignmentIssues(state,{...home,id:'over',targetHours:18},home.id).some(x=>x.includes('超え')));
const p={id:'p0',lessonId:lesson.id,week:0,day:4,period:0,locked:false};
let resolved=resolvePeriodPlacement(state,fy+'-09-25',p);
assert.equal(resolved.subjectOverride,'技術分野');assert.deepEqual(resolved.teacherIdsOverride,[tech.teacherId]);
resolved=resolvePeriodPlacement(state,fy+'-10-30',p);
assert.equal(resolved.subjectOverride,'家庭分野');assert.deepEqual(resolved.teacherIdsOverride,[home.teacherId]);
assert.equal(resolved.periodAssignmentId,home.id);
const week=weeklyPeriodOverrides(state,mondayFor(fy+'-09-30'),0);
const wed=week.find(x=>x.lessonId===lesson.id&&x.day===2),thu=week.find(x=>x.lessonId===lesson.id&&x.day===3);
assert.equal(wed.subjectOverride,'技術分野');
assert.equal(thu.subjectOverride,'家庭分野');
assert.equal(wed.teacherIdsOverride[0],tech.teacherId);
assert.equal(thu.teacherIdsOverride[0],home.teacherId);
state.timetable.placements=[p];
const estimated=estimatePeriodSchedule(state,home,calendarStats(state).byDate);
assert(estimated&&estimated.periods>0,'scheduled hours should expand fixed weekly timetable by teaching dates');
assert.equal(estimated.standardUnits,estimated.periods,'50-minute weekly periods must count as one standard unit');
const day=fy+'-10-30';
const actualRows=actualDayRows(state,{date:day,week:0,placements:resolveDatedPlacements(state,day,[p])});
assert.equal(actualRows[0].subject,'家庭分野');
assert.equal(actualRows[0].teacherIds[0],home.teacherId);
assert.equal(actualRows[0].periodAssignmentId,home.id);
saveActualDay(state,{date:day,week:0,rows:actualRows});
const progress=subjectProgress(state,3,cl.id);
const parent=progress.find(x=>x.baseSubject==='技術・家庭'&&x.isGroup);
const comp=progress.find(x=>x.isComponent&&x.subject.includes('家庭'));
assert.equal(parent.target,35);assert.equal(parent.completed,1);
assert.equal(comp.target,17);assert.equal(comp.completed,1);
assert(!progress.some(x=>x.subject==='家庭分野'&&!x.isComponent),'do not count component as an extra full subject');
assert.equal(validateState(state,calendarStats(state)).filter(x=>x.code==='PERIOD-ASSIGNMENT-INVALID').length,0);
const loaded=migrateState(JSON.parse(JSON.stringify(state)));
assert.equal(loaded.periodAssignments.length,2);
assert.equal(subjectProgress(loaded,3,cl.id).find(x=>x.isGroup).completed,1);
console.log('Period-specific subject, teacher, room, 18/17 hour allocations and actuals tests passed');
