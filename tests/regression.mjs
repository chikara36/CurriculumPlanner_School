import assert from 'node:assert/strict';
import fs from 'node:fs';
import {defaultState,migrateState,cycleSessionsForLesson} from '../model.js';
import {weeklyTargetForGrade} from '../calendar.js';
const st=defaultState(),grade=1;
assert.equal(st.schemaVersion,9);
assert(st.masters.subjects.some(x=>x.name==='理科'));
assert(st.masters.roles.some(x=>x.name==='教務'));
const stats={weeks:40,instructionDays:200};
const before=weeklyTargetForGrade(st,grade,stats);
const science=st.hourPlans.find(p=>p.grade===grade).subjects.find(x=>x.name==='理科');
science.adjustment=-20;
const after=weeklyTargetForGrade(st,grade,stats);
assert.equal(after.standardAnnual,before.standardAnnual-20);
assert(after.annual<before.annual);
const lesson=st.lessons.find(l=>l.subject==='理科'&&l.classIds.includes('c11'));
const original=cycleSessionsForLesson(st,lesson,200);
science.adjustment=20;
const afterLesson=cycleSessionsForLesson(st,lesson,200);
assert(afterLesson>=original);
const previous=defaultState();
previous.schemaVersion=8;
previous.resources.teachers[0].roles=[];
previous.resources.teachers[0].role='研究主任';
previous.masters.roles=previous.masters.roles.filter(r=>r.name!=='研究主任');
const migrated=migrateState(previous);
assert(migrated.resources.teachers[0].roles.includes('研究主任'));
assert(migrated.masters.roles.some(r=>r.name==='研究主任'));
const app=fs.readFileSync(new URL('../app.js',import.meta.url),'utf8');
assert(app.includes('data-hours-adjust'));
assert(app.includes('syncSubjectLessons'));
assert(!app.includes('l.teacherIds=tid?[tid]:[];state.timetable.placements=[]'));
assert(app.includes('if(!confirm('));
console.log('Curriculum School regression tests passed');
